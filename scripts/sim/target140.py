"""回収率 140% が何を要求するのか、算術で確定させる。

パリミュチュエルでは
    回収率 = (1 − 控除率) × (真の勝率 / 市場の含意確率)
なので、目標回収率は「市場の値付けをどれだけ誤りと見抜くか」に直結する。
"""
import math

print("=== 140% が要求する『市場の誤り』の大きさ ===")
print(f"{'目標回収率':>10} {'必要な 真の勝率/市場確率':>24}")
for t in (1.00, 1.10, 1.20, 1.40, 1.60):
    for takeout in (0.20,):
        print(f"{t*100:9.0f}% {t/(1-takeout):23.2f} 倍")
print()
print("  → 140% には、市場が **75% 過小評価** している馬を見つける必要がある。")
print("     (実測の最良セグメントは 1.0-1.5 倍帯の 87.7% = 1.10 倍どまり)")

print()
print("=== ただし高い目標ほど『検証』は容易になる ===")
print("  真の回収率が高いほど、損益分岐 100% からの距離が大きく、")
print("  少ない件数で信頼区間の下限を 100% 超にできる。")
print()
print(f"{'真の回収率':>10} {'1賭けのSD':>10} {'CI下限>100%に必要な件数':>24}")
for true_roi in (1.05, 1.20, 1.40):
    for sd in (2.8, 4.0, 6.0):
        margin = true_roi - 1.0
        if margin <= 0:
            continue
        # 1.96*sd/sqrt(n) < margin  →  n > (1.96*sd/margin)^2
        n = math.ceil((1.96 * sd / margin) ** 2)
        print(f"{true_roi*100:9.0f}% {sd:10.1f} {n:24,d} 件")
    print()
print("  → 140% なら SD=6.0 (高配当狙い) でも **約 900 件** で証明できる。")
print("     105% だと SD=2.8 でも約 12,000 件を要する。")
print("     **高い目標を掲げること自体が、検証可能性を上げる。**")
